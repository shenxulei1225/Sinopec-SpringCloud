CREATE TABLE IF NOT EXISTS `area` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `area_code` VARCHAR(64) NOT NULL COMMENT '区域编号',
  `area_name` VARCHAR(128) NOT NULL COMMENT '区域名称',
  `longitude` DOUBLE DEFAULT NULL COMMENT 'GPS经度',
  `latitude` DOUBLE DEFAULT NULL COMMENT 'GPS纬度',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '录入时间',
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最近修改时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_area_code` (`area_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci COMMENT='区域表';