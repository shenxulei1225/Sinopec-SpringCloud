CREATE TABLE IF NOT EXISTS `tag` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `area_code` VARCHAR(50) NOT NULL COMMENT '区域编码',
  `plc_partition` VARCHAR(50) NOT NULL COMMENT 'PLC分区',
  `plc_code` VARCHAR(50) NOT NULL COMMENT 'PLC编码',
  `tag_name` VARCHAR(100) NOT NULL COMMENT '标签名称',
  `tag_description` VARCHAR(255) COMMENT '标签描述',
  `read_write_mode` INT NOT NULL COMMENT '读写方式（1：read 2: write）',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '录入时间',
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最近修改时间',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci COMMENT='PLC表';