CREATE TABLE IF NOT EXISTS twin.twin_mapping_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapping_id BIGINT NOT NULL,
    operation_type VARCHAR(32) NOT NULL,
    mapping_type SMALLINT NOT NULL DEFAULT 1,
    relation_mode SMALLINT NOT NULL DEFAULT 1,
    facility_id BIGINT NOT NULL,
    actor_instance_id BIGINT NOT NULL,
    scene_id BIGINT,
    scene_code VARCHAR(64),
    bind_source VARCHAR(32),
    operation_remark VARCHAR(500),
    operator_id BIGINT,
    operator_name VARCHAR(64),
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    snapshot_json JSONB,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creator VARCHAR(64) NOT NULL DEFAULT '',
    updater VARCHAR(64) NOT NULL DEFAULT '',
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_twin_mapping_history_mapping_id
    ON twin.twin_mapping_history (mapping_id);
CREATE INDEX IF NOT EXISTS idx_twin_mapping_history_facility_id
    ON twin.twin_mapping_history (facility_id);
CREATE INDEX IF NOT EXISTS idx_twin_mapping_history_actor_instance_id
    ON twin.twin_mapping_history (actor_instance_id);
CREATE INDEX IF NOT EXISTS idx_twin_mapping_history_scene_id
    ON twin.twin_mapping_history (scene_id);
CREATE INDEX IF NOT EXISTS idx_twin_mapping_history_occurred_at
    ON twin.twin_mapping_history (occurred_at);

COMMENT ON TABLE twin.twin_mapping_history IS 'Twin 映射历史表';
COMMENT ON COLUMN twin.twin_mapping_history.mapping_id IS '主映射ID';
COMMENT ON COLUMN twin.twin_mapping_history.operation_type IS '操作类型：BIND/REBIND/UNBIND';
COMMENT ON COLUMN twin.twin_mapping_history.facility_id IS '设施ID';
COMMENT ON COLUMN twin.twin_mapping_history.actor_instance_id IS 'Actor实例ID';
COMMENT ON COLUMN twin.twin_mapping_history.scene_id IS '场景ID';
COMMENT ON COLUMN twin.twin_mapping_history.scene_code IS '场景编码';
COMMENT ON COLUMN twin.twin_mapping_history.bind_source IS '绑定来源';
COMMENT ON COLUMN twin.twin_mapping_history.operation_remark IS '操作备注';
COMMENT ON COLUMN twin.twin_mapping_history.snapshot_json IS '快照';
