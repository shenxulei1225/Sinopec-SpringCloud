INSERT INTO dynamic_entity_category_relation_t1 (
  tenant_id, category_id, entity_type_code, entity_id, domain, sort, creator, deleted
)
SELECT
  1,
  cat.id,
  'standard',
  e.id,
  NULL,
  0,
  'seed',
  false
FROM ent_standard_t1 e
JOIN dynamic_category cat
  ON cat.deleted = false AND cat.tenant_id = 1
  AND cat.code = CASE e.standard_level
    WHEN 'NATIONAL' THEN 'cat-standard-national'
    WHEN 'INDUSTRY' THEN 'cat-standard-industry'
    WHEN 'ENTERPRISE' THEN 'cat-standard-enterprise'
    ELSE 'standard_root'
  END
WHERE e.deleted = false AND e.tenant_id = 1
  AND e.code LIKE 'std-%'
  AND NOT EXISTS (
    SELECT 1 FROM dynamic_entity_category_relation_t1 r
    WHERE r.tenant_id = 1
      AND r.category_id = cat.id
      AND r.entity_type_code = 'standard'
      AND r.entity_id = e.id
      AND r.deleted = false
  );
